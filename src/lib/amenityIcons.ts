// Idea from the benchmark (limehome): every amenity gets the icon that fits it, instead of the same
// sparkle for everything the short list in src/lib/rooms.ts does not know. Order matters:
// the first match wins ("Wohnzimmer mit Sofa und Schreibtisch" is the sofa).
const RULES: Array<[RegExp, LucideIcon]> = [
  [/klima/, AirVent],
  [/dusche/, ShowerHead],
  [/\bwc\b|toilette/, Toilet],
  [/badewanne|whirlpool|wanne/, Bath],
  [/sauna|handtuch|tücher/, Droplets],
  [/slipper|hausschuh/, Footprints],
  [/bademantel/, Shirt],
  [/föhn|haartrockner/, Wind],
  [/sofa|couch|wohnzimmer|wohnbereich/, Sofa],
  [/schreibtisch|arbeitsplatz/, LampDesk],
  [/sessel|sitz/, Armchair],
  [/doppelbett|kingsize|king|boxspring|schlafzimmer/, BedDouble],
  [/einzelbett|zustellbett/, BedSingle],
  [/baby|kinderbett/, Baby],
  [/familie|kinder|personen/, Users],
  [/hund|haustier/, Dog],
  [/barrierefrei|rollstuhl/, Accessibility],
  [/meerblick|seeblick|nordsee|meer/, Waves],
  [/bergblick|berg/, Mountain],
  [/landblick|gartenblick|park|wald/, Trees],
  [/sonnenuntergang|abendsonne/, Sunset],
  [/ausblick|blick/, Eye],
  [/balkon|terrasse|loggia/, SunMedium],
  [/kamin/, Flame],
  [/heizung|fußboden/, Heater],
  [/minibar|wein|sekt/, Wine],
  [/kühlschrank/, Refrigerator],
  [/kaffee|tee|nespresso/, Coffee],
  [/küche|kochnische|pantry/, CookingPot],
  [/waschmaschine|trockner/, WashingMachine],
  [/telefon/, Phone],
  [/tv|fernseh|flachbild/, Tv],
  [/wlan|wifi|internet/, Wifi],
  [/laptop/, Laptop],
  [/safe|tresor/, Lock],
  [/garage|parkplatz|stellplatz/, Car],
  [/spa|wellness/, Sparkles],
];

export function amenityIcon(label: string): LucideIcon | null {
  const value = label.toLowerCase();
  for (const [re, icon] of RULES) if (re.test(value)) return icon;
  return null;
}
